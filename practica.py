import nltk
from nltk.chat.util import Chat, reflections

pairs = [
    ['Привет',  ['Привет!', 'Здравствуйте!', 'Добрый день!', 'Приветствую вас!']],
    ['Какая погода?', ['Сейчас посмотрю... Идет дождь.', 'На улице жарко.', 'Идёт снег']],
    ['Как тебя (зовут|называют)', ['Меня зовут SynergyBot. А тебя?']],
    ['Меня зовут (.*)', ['Приятно познакомиться, %1!', 'Здравствуйте, %1!']],
    ['Как дела?', ['У меня все хорошо, спасибо!', 'Прекрасно, а у вас?']],
    ['Что ты умеешь?', ['Я могу поддерживать разговор и отвечать на простые вопросы.']],
    ['Пока', ['До свидания!', 'До встречи!', 'Пока!', 'Увидимся!']]
]

def start_chat():
    print("Привет! Я SynergyBot. Чем могу помочь?")
    chat = Chat(pairs, reflections)
    chat.converse()

if __name__ == '__main__':
    start_chat()